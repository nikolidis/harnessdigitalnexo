// Build every Digital Nexo brand asset from logo.json (see gen.mjs):
//   - artwork.ts for the brand plugin (wordmark + monogram path data)
//   - favicon.svg / favicon-dark.svg
//   - icon-192.png / icon-512.png / icon-maskable-512.png / apple-touch-icon.png
//
// Usage (from the repository root, after `pnpm install`):
//   node digitalnexo/brand/build-assets.mjs            # writes straight into the repository
//   node digitalnexo/brand/build-assets.mjs /tmp/out    # writes everything into one folder to review
// PNG icons are rendered with the Playwright Chromium the repository already depends on; set
// DIGITALNEXO_CHROME to the path of an installed Chrome to use that one instead.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('../..', import.meta.url))
const L = JSON.parse(readFileSync(new URL('./logo.json', import.meta.url)))
const review = process.argv[2]
const out = review ?? fileURLToPath(new URL('./.out', import.meta.url))
mkdirSync(out, { recursive: true })

async function launch() {
  const { chromium } = createRequire(`${ROOT}apps/web/package.json`)('playwright')
  const executablePath = process.env.DIGITALNEXO_CHROME
  return chromium.launch({ headless: true, ...(executablePath === undefined ? {} : { executablePath }) })
}

// Brand colours taken from the website theme (src/styles.css):
//   --foreground: oklch(0.25 0.013 260) -> #1e2228 ; --accent: oklch(0.45 0.065 30) -> #754740
// The light accent is the same hue raised to L=0.76 so the period stays visible on dark surfaces.
export const INK = '#1e2228'
export const PAPER = '#ffffff'
export const ACCENT = '#754740'
export const ACCENT_LIGHT = '#e59c8f'

const TILE = 160
const TILE_RADIUS = 36
const round = n => Math.round(n * 1000) / 1000

/** Monogram placement inside the square tile: glyph height is `ratio` of the tile edge. */
function tilePlacement(ratio) {
  const scale = (TILE * ratio) / L.monogram.height
  const width = L.monogram.width * scale
  const height = L.monogram.height * scale
  return { scale: round(scale), x: round((TILE - width) / 2), y: round((TILE - height) / 2) }
}
const NORMAL = tilePlacement(0.56)
const MASKABLE = tilePlacement(0.42)

function tileSvg({ tile, glyph, accent, radius = TILE_RADIUS, placement = NORMAL, size = TILE }) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${TILE} ${TILE}" fill="none">`
    + `<rect width="${TILE}" height="${TILE}" rx="${radius}" fill="${tile}"/>`
    + `<g transform="translate(${placement.x} ${placement.y}) scale(${placement.scale})">`
    + `<path d="${L.monogram.letters}" fill="${glyph}"/><path d="${L.monogram.dot}" fill="${accent}"/></g></svg>\n`
}

// 1. Favicons: dark tile for light browser chrome, light tile for dark chrome.
writeFileSync(`${out}/favicon.svg`, tileSvg({ tile: INK, glyph: PAPER, accent: ACCENT_LIGHT }))
writeFileSync(`${out}/favicon-dark.svg`, tileSvg({ tile: '#f4f4f5', glyph: INK, accent: ACCENT }))

// 2. PNG icons rendered by headless Chrome from the same SVG.
const browser = await launch()
async function png(name, size, svg, transparent) {
  const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 })
  await page.setContent(`<html><body style="margin:0;background:transparent">${svg.replace('<svg ', `<svg style="display:block" `)}</body></html>`)
  await page.screenshot({ path: `${out}/${name}`, omitBackground: transparent, clip: { x: 0, y: 0, width: size, height: size } })
  await page.close()
}
await png('icon-192.png', 192, tileSvg({ tile: INK, glyph: PAPER, accent: ACCENT_LIGHT, size: 192 }), true)
await png('icon-512.png', 512, tileSvg({ tile: INK, glyph: PAPER, accent: ACCENT_LIGHT, size: 512 }), true)
await png('icon-maskable-512.png', 512, tileSvg({ tile: INK, glyph: PAPER, accent: ACCENT_LIGHT, radius: 0, placement: MASKABLE, size: 512 }), false)
await png('apple-touch-icon.png', 180, tileSvg({ tile: INK, glyph: PAPER, accent: ACCENT_LIGHT, radius: 0, size: 180 }), false)
await browser.close()

// 3. Artwork module for the brand plugin.
const artwork = `/**
 * Digital Nexo brand artwork as vector outlines.
 *
 * Generated by digitalnexo/brand/build-assets.mjs from the website's own logo recipe:
 * "DIGITALNEXO" in Inter ExtraBold (${L.font.version}), letter-spacing -0.05em, followed by
 * an accent-coloured period. Inter is licensed under the SIL Open Font License 1.1; outlines
 * converted for a logo carry no font software. Do not edit by hand; regenerate instead.
 *
 * @module @digitalnexo/dsh-client-ui-brand/src/client/artwork
 */

/** One piece of artwork: its native box and the two fills it is drawn with. */
export interface BrandArtwork {
  /** Native width in user units. */
  readonly width: number
  /** Native height in user units. */
  readonly height: number
  /** Path data for the lettering. */
  readonly letters: string
  /** Path data for the trailing accent period. */
  readonly dot: string
}

/** The full "DIGITALNEXO." wordmark; cap height is 100 user units. */
export const WORDMARK: BrandArtwork = {
  width: ${L.wordmark.width},
  height: ${L.wordmark.height},
  letters: '${L.wordmark.letters}',
  dot: '${L.wordmark.dot}',
}

/** The "D." monogram used inside the square tile; cap height is 100 user units. */
export const MONOGRAM: BrandArtwork = {
  width: ${L.monogram.width},
  height: ${L.monogram.height},
  letters: '${L.monogram.letters}',
  dot: '${L.monogram.dot}',
}

/** Edge of the square tile's coordinate system. */
export const TILE_EDGE = ${TILE}

/** Corner radius of the tile, in tile units. */
export const TILE_RADIUS = ${TILE_RADIUS}

/** Monogram placement inside the tile: translate first, then scale. */
export const TILE_MONOGRAM = { x: ${NORMAL.x}, y: ${NORMAL.y}, scale: ${NORMAL.scale} } as const
`
writeFileSync(`${out}/artwork.ts`, artwork)

if (review === undefined) {
  copyFileSync(`${out}/artwork.ts`, `${ROOT}packages/client/ui-brand-digitalnexo/src/client/artwork.ts`)
  for (const name of ['favicon.svg', 'favicon-dark.svg', 'icon-192.png', 'icon-512.png', 'icon-maskable-512.png', 'apple-touch-icon.png']) {
    copyFileSync(`${out}/${name}`, `${ROOT}apps/web/public/${name}`)
  }
  console.log('brand assets written into the repository; rebuild with `pnpm run build`')
} else {
  console.log('brand assets written to', out)
}
